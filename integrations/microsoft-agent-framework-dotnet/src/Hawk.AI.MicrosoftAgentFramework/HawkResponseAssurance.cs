using System.Collections.ObjectModel;
using System.Text.Json;

namespace Hawk.AI.MicrosoftAgentFramework;

/// <summary>Typed digest-bound result returned by a trusted banking function.</summary>
public sealed class StructuredBankingResultEnvelope
{
    /// <summary>Creates and deep-freezes one trusted banking result envelope.</summary>
    public StructuredBankingResultEnvelope(
        string AiTransactionId,
        string ActionId,
        string CustomerFingerprint,
        string AccountFingerprint,
        string ToolFingerprint,
        string ResultSchema,
        string ResultVersion,
        IReadOnlyList<string> ApprovedFields,
        IReadOnlyDictionary<string, string> FieldClassifications,
        IReadOnlyDictionary<string, object?> Claims,
        string ResultDigest,
        string ExecutionStatus)
    {
        this.AiTransactionId = Require(AiTransactionId, nameof(AiTransactionId), 64);
        this.ActionId = Require(ActionId, nameof(ActionId), 64);
        this.CustomerFingerprint = Require(
            CustomerFingerprint,
            nameof(CustomerFingerprint),
            80);
        this.AccountFingerprint = Require(
            AccountFingerprint,
            nameof(AccountFingerprint),
            80);
        this.ToolFingerprint = Require(ToolFingerprint, nameof(ToolFingerprint), 128);
        this.ResultSchema = Require(ResultSchema, nameof(ResultSchema), 128);
        this.ResultVersion = Require(ResultVersion, nameof(ResultVersion), 64);
        this.ApprovedFields = Array.AsReadOnly(
            ApprovedFields?.ToArray()
            ?? throw new ArgumentNullException(nameof(ApprovedFields)));
        this.FieldClassifications = new ReadOnlyDictionary<string, string>(
            new Dictionary<string, string>(
                FieldClassifications
                ?? throw new ArgumentNullException(nameof(FieldClassifications)),
                StringComparer.Ordinal));
        this.Claims = FreezeClaims(Claims);
        this.ResultDigest = Require(ResultDigest, nameof(ResultDigest), 64);
        this.ExecutionStatus = Require(ExecutionStatus, nameof(ExecutionStatus), 32);
    }

    /// <summary>End-to-end transaction identifier.</summary>
    public string AiTransactionId { get; }
    /// <summary>Action correlated to the Decision Receipt.</summary>
    public string ActionId { get; }
    /// <summary>Pseudonymous customer fingerprint.</summary>
    public string CustomerFingerprint { get; }
    /// <summary>Pseudonymous account fingerprint.</summary>
    public string AccountFingerprint { get; }
    /// <summary>Receipt-bound tool or route fingerprint.</summary>
    public string ToolFingerprint { get; }
    /// <summary>Trusted result schema.</summary>
    public string ResultSchema { get; }
    /// <summary>Trusted result schema version.</summary>
    public string ResultVersion { get; }
    /// <summary>Fields the trusted source permits in the response.</summary>
    public IReadOnlyList<string> ApprovedFields { get; }
    /// <summary>Trusted field classifications.</summary>
    public IReadOnlyDictionary<string, string> FieldClassifications { get; }
    /// <summary>Deep-frozen structured source claims.</summary>
    public IReadOnlyDictionary<string, object?> Claims { get; }
    /// <summary>Digest generated by the trusted banking function.</summary>
    public string ResultDigest { get; }
    /// <summary>Actual trusted function execution status.</summary>
    public string ExecutionStatus { get; }

    private static string Require(string? value, string parameterName, int maximum)
    {
        string normalized = value?.Trim() ?? string.Empty;
        if (normalized.Length == 0 || normalized.Length > maximum)
        {
            throw new ArgumentException("A bounded non-empty value is required.", parameterName);
        }

        return normalized;
    }

    internal static IReadOnlyDictionary<string, object?> FreezeClaims(
        IReadOnlyDictionary<string, object?> claims)
    {
        ArgumentNullException.ThrowIfNull(claims);
        JsonElement serialized = JsonSerializer.SerializeToElement(claims, BankingJson.Options);
        if (serialized.ValueKind != JsonValueKind.Object)
        {
            throw new ArgumentException("Structured banking claims must be an object.", nameof(claims));
        }

        var frozen = new Dictionary<string, object?>(StringComparer.Ordinal);
        foreach (JsonProperty property in serialized.EnumerateObject())
        {
            frozen.Add(property.Name, property.Value.Clone());
        }

        return new ReadOnlyDictionary<string, object?>(frozen);
    }
}

/// <summary>Claimed response evidence origin; stronger grades require server verification.</summary>
public sealed record HawkResponseEvidenceSource(
    string ClaimedGrade,
    string SourceId,
    string? KeyId = null,
    string? Attestation = null);

/// <summary>Exact structured response material sent to Hawk before release.</summary>
public sealed class BankingResponseAssuranceMaterial
{
    /// <summary>Creates and deep-freezes one response assurance request.</summary>
    public BankingResponseAssuranceMaterial(
        string DecisionReceiptId,
        string AuthorizedCustomerFingerprint,
        string AuthorizedAccountFingerprint,
        StructuredBankingResultEnvelope TrustedResult,
        IReadOnlyDictionary<string, object?> CandidateClaims,
        int RegenerationAttempt,
        HawkResponseEvidenceSource EvidenceSource)
    {
        this.DecisionReceiptId = Require(DecisionReceiptId, nameof(DecisionReceiptId), 36);
        this.AuthorizedCustomerFingerprint = Require(
            AuthorizedCustomerFingerprint,
            nameof(AuthorizedCustomerFingerprint),
            80);
        this.AuthorizedAccountFingerprint = Require(
            AuthorizedAccountFingerprint,
            nameof(AuthorizedAccountFingerprint),
            80);
        this.TrustedResult = TrustedResult
            ?? throw new ArgumentNullException(nameof(TrustedResult));
        this.CandidateClaims = StructuredBankingResultEnvelope.FreezeClaims(CandidateClaims);
        if (RegenerationAttempt is < 0 or > 1)
        {
            throw new ArgumentOutOfRangeException(
                nameof(RegenerationAttempt),
                "At most one regeneration attempt is supported.");
        }

        this.RegenerationAttempt = RegenerationAttempt;
        this.EvidenceSource = EvidenceSource
            ?? throw new ArgumentNullException(nameof(EvidenceSource));
    }

    /// <summary>Existing Hawk Decision Receipt.</summary>
    public string DecisionReceiptId { get; }
    /// <summary>Pseudonymous customer scope from the trusted subject.</summary>
    public string AuthorizedCustomerFingerprint { get; }
    /// <summary>Pseudonymous account scope from the trusted subject.</summary>
    public string AuthorizedAccountFingerprint { get; }
    /// <summary>Trusted banking function result.</summary>
    public StructuredBankingResultEnvelope TrustedResult { get; }
    /// <summary>Deep-frozen candidate response claims.</summary>
    public IReadOnlyDictionary<string, object?> CandidateClaims { get; }
    /// <summary>Zero for the original response or one for the only permitted retry.</summary>
    public int RegenerationAttempt { get; }
    /// <summary>Claimed evidence source for server-side verification.</summary>
    public HawkResponseEvidenceSource EvidenceSource { get; }

    /// <summary>Returns correlation only; subject, account, and claims are redacted.</summary>
    public override string ToString() =>
        $"BankingResponseAssuranceMaterial {{ DecisionReceiptId = {DecisionReceiptId}, " +
        $"ActionId = {TrustedResult.ActionId}, SensitiveMaterial = [REDACTED] }}";

    internal BankingResponseAssuranceMaterial WithCandidate(
        IReadOnlyDictionary<string, object?> candidate,
        int attempt) => new(
            DecisionReceiptId,
            AuthorizedCustomerFingerprint,
            AuthorizedAccountFingerprint,
            TrustedResult,
            candidate,
            attempt,
            EvidenceSource);

    private static string Require(string? value, string parameterName, int maximum)
    {
        string normalized = value?.Trim() ?? string.Empty;
        if (normalized.Length == 0 || normalized.Length > maximum)
        {
            throw new ArgumentException("A bounded non-empty value is required.", parameterName);
        }

        return normalized;
    }
}

/// <summary>Hawk's deterministic response release decision and safe evidence projection.</summary>
public sealed record StructuredBankingResponseDecision(
    string Decision,
    string ReasonCode,
    string Assurance,
    string EvidenceGrade,
    IReadOnlyList<string> ComparedFields,
    IReadOnlyList<string> MismatchFields,
    IReadOnlyList<string> RedactedFields,
    JsonElement? SafeResponse,
    bool ShouldRegenerate,
    string TrustedResultDigest,
    string CandidateResponseHash,
    string DecisionReceiptId,
    string EvidenceNodeId,
    JsonElement Evidence);

/// <summary>Separate structured-response control contract.</summary>
public interface IHawkResponseAssuranceClient
{
    /// <summary>Validates structured response claims before they are released.</summary>
    Task<StructuredBankingResponseDecision> AssureStructuredResponseAsync(
        BankingResponseAssuranceMaterial material,
        CancellationToken cancellationToken);
}

/// <summary>Result released by the local gate only after Hawk response assurance.</summary>
public sealed record HawkAssuredBankingResponse(
    string Decision,
    string ReasonCode,
    bool Released,
    JsonElement? ResponseClaims,
    bool EvidenceComplete,
    string? EvidenceNodeId)
{
    /// <summary>Returns status only and never formats response claims.</summary>
    public override string ToString() =>
        $"HawkAssuredBankingResponse {{ Decision = {Decision}, Released = {Released}, " +
        "ResponseClaims = [REDACTED] }";
}

/// <summary>Deterministic release gate with at most one Hawk-validated regeneration.</summary>
public sealed class HawkStructuredResponseGate
{
    private readonly IHawkResponseAssuranceClient _hawk;

    /// <summary>Creates a response gate over the separate assurance client.</summary>
    public HawkStructuredResponseGate(IHawkResponseAssuranceClient hawk)
    {
        _hawk = hawk ?? throw new ArgumentNullException(nameof(hawk));
    }

    /// <summary>
    /// Validates the original response, performs at most one configured regeneration,
    /// validates the replacement, and releases only Hawk-approved structured material.
    /// </summary>
    public async ValueTask<HawkAssuredBankingResponse> AssureAsync(
        BankingResponseAssuranceMaterial material,
        Func<int, CancellationToken, ValueTask<IReadOnlyDictionary<string, object?>>>? regenerate,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(material);
        StructuredBankingResponseDecision decision = await _hawk
            .AssureStructuredResponseAsync(material, cancellationToken)
            .ConfigureAwait(false);
        BankingResponseAssuranceMaterial releaseMaterial = material;
        if (decision.Decision == "regenerate")
        {
            if (!decision.ShouldRegenerate || regenerate is null || material.RegenerationAttempt != 0)
            {
                return Denied(decision);
            }

            IReadOnlyDictionary<string, object?> replacement = await regenerate(
                    1,
                    cancellationToken)
                .ConfigureAwait(false);
            releaseMaterial = material.WithCandidate(replacement, 1);
            decision = await _hawk
                .AssureStructuredResponseAsync(releaseMaterial, cancellationToken)
                .ConfigureAwait(false);
            if (decision.Decision == "regenerate")
            {
                return new HawkAssuredBankingResponse(
                    "block",
                    "BANKING_REGENERATION_LIMIT_EXCEEDED",
                    Released: false,
                    ResponseClaims: null,
                    EvidenceComplete: false,
                    decision.EvidenceNodeId);
            }
        }

        return Release(decision, releaseMaterial);
    }

    private static HawkAssuredBankingResponse Release(
        StructuredBankingResponseDecision decision,
        BankingResponseAssuranceMaterial material)
    {
        if (decision.Decision == "allow")
        {
            return new HawkAssuredBankingResponse(
                decision.Decision,
                decision.ReasonCode,
                Released: true,
                JsonSerializer.SerializeToElement(material.CandidateClaims, BankingJson.Options),
                EvidenceComplete: true,
                decision.EvidenceNodeId);
        }

        if (decision.Decision is "redact" or "safe_fallback")
        {
            if (decision.SafeResponse is null
                || decision.SafeResponse.Value.ValueKind != JsonValueKind.Object)
            {
                return new HawkAssuredBankingResponse(
                    "block",
                    "BANKING_SAFE_RESPONSE_UNAVAILABLE",
                    Released: false,
                    ResponseClaims: null,
                    EvidenceComplete: false,
                    decision.EvidenceNodeId);
            }

            return new HawkAssuredBankingResponse(
                decision.Decision,
                decision.ReasonCode,
                Released: true,
                decision.SafeResponse.Value.Clone(),
                EvidenceComplete: true,
                decision.EvidenceNodeId);
        }

        return Denied(decision);
    }

    private static HawkAssuredBankingResponse Denied(
        StructuredBankingResponseDecision decision) => new(
            decision.Decision,
            decision.ReasonCode,
            Released: false,
            ResponseClaims: null,
            EvidenceComplete: !string.IsNullOrWhiteSpace(decision.EvidenceNodeId),
            decision.EvidenceNodeId);
}
