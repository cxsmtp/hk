from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any
import xml.etree.ElementTree as ET


def _load_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def _load_junit(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {"tests": 0, "failures": 0, "errors": 0, "skipped": 0, "failed_tests": []}

    tree = ET.parse(path)
    root = tree.getroot()
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))

    totals = {"tests": 0, "failures": 0, "errors": 0, "skipped": 0}
    failed_tests: list[str] = []
    for suite in suites:
        totals["tests"] += int(suite.attrib.get("tests", "0"))
        totals["failures"] += int(suite.attrib.get("failures", "0"))
        totals["errors"] += int(suite.attrib.get("errors", "0"))
        totals["skipped"] += int(suite.attrib.get("skipped", "0"))
        for case in suite.findall("testcase"):
            if case.find("failure") is not None or case.find("error") is not None:
                classname = str(case.attrib.get("classname") or "").strip()
                name = str(case.attrib.get("name") or "").strip()
                failed_tests.append(f"{classname}::{name}".strip(":"))
    totals["failed_tests"] = failed_tests
    return totals


def main() -> int:
    parser = argparse.ArgumentParser(description="Print deterministic e2e harness summary.")
    parser.add_argument("--summary", required=True, help="Path to JSON summary generated by e2e integration test")
    parser.add_argument("--junit", required=True, help="Path to pytest JUnit XML")
    parser.add_argument("--pytest-exit-code", type=int, required=True, help="Exit code returned by pytest run")
    args = parser.parse_args()

    summary_path = Path(args.summary).resolve()
    junit_path = Path(args.junit).resolve()

    e2e_summary = _load_json(summary_path)
    junit = _load_junit(junit_path)

    full_pass = args.pytest_exit_code == 0 and bool(e2e_summary.get("pass", False))
    failed_stage = str(e2e_summary.get("failed_stage") or "")
    if not failed_stage and (junit.get("failures", 0) or junit.get("errors", 0)):
        failed_tests = junit.get("failed_tests") or []
        failed_stage = str(failed_tests[0] if failed_tests else "pytest_suite")
    if not failed_stage and not full_pass:
        failed_stage = "unknown"

    correlation_ids = sorted(
        {
            str(item).strip()
            for item in (e2e_summary.get("correlation_ids_generated") or [])
            if str(item).strip()
        }
    )

    print("===== E2E Harness Summary =====")
    print(f"pass: {'true' if full_pass else 'false'}")
    print(f"failed_stage: {failed_stage or 'none'}")
    print(f"correlation_ids_generated: {len(correlation_ids)}")
    if correlation_ids:
        print("correlation_ids:")
        for value in correlation_ids:
            print(f"- {value}")
    print("---")
    print(f"tests_run: {junit.get('tests', 0)}")
    print(f"tests_failed: {int(junit.get('failures', 0)) + int(junit.get('errors', 0))}")
    print(f"tests_skipped: {junit.get('skipped', 0)}")
    failed_tests = junit.get("failed_tests") or []
    if failed_tests:
        print("failed_tests:")
        for test_name in failed_tests:
            print(f"- {test_name}")

    return 0 if full_pass else 1


if __name__ == "__main__":
    raise SystemExit(main())
